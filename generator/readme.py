"""Writes README.md from profile.yml: nothing but linked, theme-aware images.

    python -m generator.readme            # rewrite README.md
    python -m generator.readme --check    # exit 1 if README.md is stale (used in tests/CI)
"""
from __future__ import annotations

import argparse
import sys

from .config import ROOT, Config, load

BRANCH = "output"


class Readme:
    def __init__(self, cfg: Config, base: str | None = None):
        self.cfg = cfg
        self.base = base or f"https://raw.githubusercontent.com/{cfg.login}/{cfg.login}/{BRANCH}"

    def picture(self, stem: str, alt: str, *, width: str | None = None, height: int | None = None, ext: str = "svg") -> str:
        size = f' width="{width}"' if width else f' height="{height}"' if height else ""
        return (
            "<picture>"
            f'<source media="(prefers-color-scheme: dark)" srcset="{self.base}/{stem}-dark.{ext}">'
            f'<source media="(prefers-color-scheme: light)" srcset="{self.base}/{stem}-light.{ext}">'
            f'<img alt="{alt}" src="{self.base}/{stem}-dark.{ext}"{size}>'
            "</picture>"
        )

    def linked(self, url: str, picture: str) -> str:
        return f'<a href="{url}">{picture}</a>'

    def render(self) -> str:
        cfg = self.cfg
        profile = f"https://github.com/{cfg.login}"
        p = self.picture
        roles = " · ".join(cfg.roles)
        buttons = "\n".join(
            self.linked(link.url, p(f"btn-{link.id}", link.label, height=44)) for link in cfg.links
        )
        projects = "\n".join(
            self.linked(f"{profile}/{name}", p(f"project-{name}", f"{name} repository", width="32%"))
            for name in cfg.featured
        )
        blocks = [
            p("hero", f"{cfg.name} — {roles}", width="100%"),
            buttons,
            p("about", f"About {cfg.name}", width="100%"),
            p("stats", "GitHub stats: contributions, commits, pull requests, reviews, streaks", width="100%"),
            p("city", "Contribution City: the last 12 months as a rotating 3D city", width="100%", ext="gif"),
            p("calendar", "Contribution calendar of the last 12 months", width="100%"),
            p("pulse", "Weekly contribution heartbeat", width="100%"),
            p("languages", "Most used languages", width="49%") + "\n" + p("clock", "Commit activity by hour", width="49%"),
            p("departures", "Recent activity board", width="100%"),
            projects,
            p("stack", "Tech stack", width="100%"),
            p("achievements", "Achievements", width="100%"),
            p("nightly", "Nightly build status and tonight's weather in Berlin", width="49%") + "\n"
            + p("quote", "Quote of the night", width="49%"),
            self.linked(f"{profile}#{cfg.login}", p("footer", "Thanks for stopping by", width="100%")),
        ]
        body = "\n\n".join(blocks)
        return (
            "<!--\n"
            "  Generated by `python -m generator.readme` from profile.yml. Do not edit by hand.\n"
            f"  Every image is re-rendered nightly by .github/workflows/profile.yml and served from the `{BRANCH}` branch.\n"
            "-->\n"
            f'<div align="center">\n\n{body}\n\n</div>\n'
        )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="generator.readme")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    content = Readme(load()).render()
    path = ROOT / "README.md"
    if args.check:
        if path.read_text(encoding="utf-8") != content:
            print("README.md is out of date — run: python -m generator.readme", file=sys.stderr)
            return 1
        return 0
    path.write_text(content, encoding="utf-8")
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
